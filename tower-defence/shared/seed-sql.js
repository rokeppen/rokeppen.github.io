// Turns app-shape {weapons, enemies, levels} into idempotent upsert SQL for Supabase.
import { weaponToRow, enemyToRow, levelToRow } from './mapping.js';

// Columns that are Postgres reserved words and must be quoted.
const RESERVED = new Set(['end']);
const ident = (name) => (RESERVED.has(name) ? `"${name}"` : name);
const quote = (s) => `'${String(s).replaceAll("'", "''")}'`;

// The only text[] column; every other array/object column is jsonb.
const TEXT_ARRAY_COLUMNS = new Set(['weapon_ids']);

export function sqlLiteral(value, { textArray = false } = {}) {
  if (value === null || value === undefined) return 'null';
  if (typeof value === 'number' || typeof value === 'boolean') return String(value);
  if (typeof value === 'string') return quote(value);
  if (textArray && Array.isArray(value)) {
    return `array[${value.map(quote).join(', ')}]::text[]`;
  }
  return `${quote(JSON.stringify(value))}::jsonb`;
}

function upsertSql(table, row) {
  const cols = Object.keys(row);
  const values = cols.map(c => sqlLiteral(row[c], { textArray: TEXT_ARRAY_COLUMNS.has(c) }));
  const updates = cols.filter(c => c !== 'id').map(c => `${ident(c)} = excluded.${ident(c)}`);
  return `insert into public.${table} (${cols.map(ident).join(', ')})\n` +
    `values (${values.join(', ')})\n` +
    `on conflict (id) do update set ${updates.join(', ')};`;
}

export function toSeedSql({ weapons = [], enemies = [], levels = [] }) {
  const parts = [
    '-- Generated by `npm run seed` from fallback-data.json. Do not edit by hand.',
    ...weapons.map(w => upsertSql('weapons', weaponToRow(w))),
    ...enemies.map(e => upsertSql('enemies', enemyToRow(e))),
    ...levels.map(l => upsertSql('levels', levelToRow(l))),
  ];
  return parts.join('\n\n') + '\n';
}
