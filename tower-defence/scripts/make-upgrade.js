// Usage: npm run upgrade-sql  (from tower-defence/)
// Concatenates the beer-party migration and seed.sql into one file for existing projects.
import { readFileSync, writeFileSync } from 'node:fs';

const migration = new URL('../supabase/migrations/2026-11-25-beer-party.sql', import.meta.url);
const seed = new URL('../supabase/seed.sql', import.meta.url);
const target = new URL('../supabase/upgrade-beer-party.sql', import.meta.url);

const header =
  '-- Upgrade an existing Supabase project to the beer party. Safe to re-run.\n' +
  '-- Paste into the SQL editor and run once.\n' +
  '-- Generated by `npm run upgrade-sql`: the migration followed by seed.sql.\n\n';

const join = (s) => (s.endsWith('\n') ? s : `${s}\n`);
writeFileSync(
  target,
  header + join(readFileSync(migration, 'utf8')) + '\n' + join(readFileSync(seed, 'utf8')),
);
console.log('Wrote supabase/upgrade-beer-party.sql (migration + seed).');
